// Package stress generates a chain of interlinked packages to load the
// language server: indexing, cross-package references, and completion over a
// method set that grows with every embedded level.
package stress

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"text/template"
)

// Dir is where packages are generated, relative to the module root.
const Dir = "lsp/stress"

// MethodsPerPkg is the number of methods each level adds to Node.
const MethodsPerPkg = 20

var pkgTmpl = template.Must(template.New("pkg").Parse(`// Code generated by lab stress. DO NOT EDIT.
package {{.Name}}
{{if .Prev}}
import prev "{{.Module}}/` + Dir + `/{{.Prev}}"

type Node struct {
	prev.Node
	Level{{.I}} int
}

func Depth() int { return prev.Depth() + 1 }
{{else}}
type Node struct{ Level0 int }

func Depth() int { return 0 }
{{end}}
{{range .Methods}}
func (n *Node) Method{{$.I}}_{{.}}(x int) int { return x + n.Level{{$.I}} + {{.}} }
{{end}}
type Item{{.I}}[T any] struct{ Value T }

func (it Item{{.I}}[T]) Get() T { return it.Value }
`))

var mainTmpl = template.Must(template.New("main").Parse(`// Code generated by lab stress. DO NOT EDIT.
package main

import (
	"fmt"

	leaf "{{.Module}}/` + Dir + `/{{.Last}}"
)

func main() {
	var n leaf.Node
	// Completion on "n." lists {{.Total}} promoted methods.
	fmt.Println("depth", leaf.Depth(), n.Method{{.LastI}}_0(1))
}
`))

// Generate writes n packages plus a main package under root/Dir, replacing previous output.
func Generate(root, module string, n int) (string, error) {
	if n < 1 {
		return "", fmt.Errorf("n must be >= 1")
	}
	out := filepath.Join(root, Dir)
	if err := os.RemoveAll(out); err != nil {
		return "", err
	}
	methods := make([]int, MethodsPerPkg)
	for i := range methods {
		methods[i] = i
	}
	name := func(i int) string { return fmt.Sprintf("p%04d", i) }
	for i := range n {
		data := map[string]any{"Name": name(i), "Module": module, "I": i, "Methods": methods, "Prev": ""}
		if i > 0 {
			data["Prev"] = name(i - 1)
		}
		if err := write(filepath.Join(out, name(i), name(i)+".go"), pkgTmpl, data); err != nil {
			return "", err
		}
	}
	data := map[string]any{"Module": module, "Last": name(n - 1), "LastI": n - 1, "Total": n * MethodsPerPkg}
	return out, write(filepath.Join(out, "main", "main.go"), mainTmpl, data)
}

func write(path string, t *template.Template, data any) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	var b strings.Builder
	if err := t.Execute(&b, data); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(b.String()), 0o644)
}
